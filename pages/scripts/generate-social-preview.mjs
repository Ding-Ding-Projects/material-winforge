import { copyFile, mkdir, readFile, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(siteRoot, "public");
const repositoryRoot = path.resolve(siteRoot, "..");
const icon = await readFile(path.join(publicDir, "app-icon.svg"));
const iconData = icon.toString("base64");
const output = path.join(publicDir, "og.png");
const temporary = path.join(publicDir, ".og.tmp.png");

const card = `
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    <linearGradient id="background" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#07150d"/>
      <stop offset="0.54" stop-color="#123721"/>
      <stop offset="1" stop-color="#1f5a30"/>
    </linearGradient>
    <radialGradient id="glow" cx="70%" cy="22%" r="65%">
      <stop offset="0" stop-color="#9de7ae" stop-opacity="0.24"/>
      <stop offset="1" stop-color="#9de7ae" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="1200" height="630" fill="url(#background)"/>
  <rect width="1200" height="630" fill="url(#glow)"/>
  <circle cx="1022" cy="98" r="184" fill="#c8f7d3" fill-opacity="0.08"/>
  <circle cx="1120" cy="542" r="268" fill="#ffe08a" fill-opacity="0.06"/>
  <rect x="72" y="72" width="1056" height="486" rx="44" fill="#f4fff5" fill-opacity="0.075" stroke="#d8ffe0" stroke-opacity="0.16" stroke-width="2"/>
  <image href="data:image/svg+xml;base64,${iconData}" x="112" y="127" width="208" height="208"/>
  <text x="368" y="194" fill="#d8ffe0" font-family="Segoe UI, Arial, sans-serif" font-size="28" font-weight="650" letter-spacing="3">WINFORGE</text>
  <text x="368" y="277" fill="#ffffff" font-family="Segoe UI, Arial, sans-serif" font-size="63" font-weight="720">Material 3 Preview</text>
  <text x="368" y="333" fill="#c7d8ca" font-family="Segoe UI, Arial, sans-serif" font-size="27">Desktop design preview, documentation, and verified release links.</text>
  <rect x="112" y="400" width="690" height="84" rx="28" fill="#b7f1c3"/>
  <text x="154" y="453" fill="#0b2b15" font-family="Segoe UI, Arial, sans-serif" font-size="30" font-weight="650">Preview the interface. Install only a published build.</text>
</svg>`;

await mkdir(publicDir, { recursive: true });
await sharp(Buffer.from(card))
  .png({ compressionLevel: 9, adaptiveFiltering: false, palette: false })
  .toFile(temporary);
await rm(output, { force: true });
await copyFile(temporary, output);
await copyFile(temporary, path.join(repositoryRoot, "social-preview.png"));
await rm(temporary, { force: true });

console.log("Generated byte-identical public/og.png and ../social-preview.png (1200x630). ");
